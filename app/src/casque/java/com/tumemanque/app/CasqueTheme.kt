/** Bouton rond avec une icône. */
@Composable
fun RoundBtn(
    icon: ImageVector, onClick: () -> Unit, modifier: Modifier = Modifier, size: Dp = 44.dp, iconSize: Dp = 22.dp,
    tint: Color = P.text, fill: Color = P.card,
) {
    Box(
        modifier.size(size).clip(CircleShape).background(fill).clickable { onClick() },
        contentAlignment = Alignment.Center,
    ) { CIcon(icon, tint, iconSize) }
}
