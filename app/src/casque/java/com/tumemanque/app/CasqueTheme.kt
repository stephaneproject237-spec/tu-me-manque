    val b = ImageVector.Builder(defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f)
    // Un tracé mal écrit ne doit jamais faire planter l'appli : l'icône est alors simplement vide.
